using Carter;
using CrdbLab.Api.Data;
using CrdbLab.Api.Models;
using Microsoft.EntityFrameworkCore;
using Npgsql;

namespace CrdbLab.Api.Endpoints;

public class CustomerModule : ICarterModule
{
    public void AddRoutes(IEndpointRouteBuilder app)
    {
        var customers = app.MapGroup("/customers").WithTags("Customers");

        customers.MapGet("/", async (BankDbContext db) =>
            await db.Customers.AsNoTracking()
                .OrderBy(c => c.Name)
                .Select(c => new CustomerResponse(c.Id, c.Name))
                .ToListAsync());

        customers.MapGet("/{id:guid}", async (Guid id, BankDbContext db) =>
        {
            var customer = await db.Customers.AsNoTracking()
                .Where(c => c.Id == id)
                .Select(c => new CustomerResponse(c.Id, c.Name))
                .FirstOrDefaultAsync();

            return customer is null ? Results.NotFound() : Results.Ok(customer);
        })
        .Produces<CustomerResponse>()
        .Produces(StatusCodes.Status404NotFound);

        customers.MapPost("/", async (CustomerRequest request, BankDbContext db) =>
        {
            if (string.IsNullOrWhiteSpace(request.Name))
                return Results.BadRequest("Name is required.");

            var customer = new Customer { Name = request.Name.Trim() };
            db.Customers.Add(customer);
            await db.SaveChangesAsync(); // Id is generated by CockroachDB and read back

            return Results.Created($"/customers/{customer.Id}", new CustomerResponse(customer.Id, customer.Name));
        })
        .Produces<CustomerResponse>(StatusCodes.Status201Created)
        .Produces(StatusCodes.Status400BadRequest);

        customers.MapPut("/{id:guid}", async (Guid id, CustomerRequest request, BankDbContext db) =>
        {
            if (string.IsNullOrWhiteSpace(request.Name))
                return Results.BadRequest("Name is required.");

            var customer = await db.Customers.FindAsync(id);
            if (customer is null)
                return Results.NotFound();

            customer.Name = request.Name.Trim();
            await db.SaveChangesAsync();

            return Results.Ok(new CustomerResponse(customer.Id, customer.Name));
        })
        .Produces<CustomerResponse>()
        .Produces(StatusCodes.Status400BadRequest)
        .Produces(StatusCodes.Status404NotFound);

        customers.MapDelete("/{id:guid}", async (Guid id, BankDbContext db) =>
        {
            try
            {
                var deleted = await db.Customers.Where(c => c.Id == id).ExecuteDeleteAsync();
                return deleted == 0 ? Results.NotFound() : Results.NoContent();
            }
            catch (PostgresException ex) when (ex.SqlState == PostgresErrorCodes.ForeignKeyViolation)
            {
                return Results.Conflict("Customer still has transactions.");
            }
        })
        .Produces(StatusCodes.Status204NoContent)
        .Produces(StatusCodes.Status404NotFound)
        .Produces(StatusCodes.Status409Conflict);
    }
}
