using Carter;
using CrdbLab.Api.Data;
using CrdbLab.Api.Models;
using Microsoft.EntityFrameworkCore;
using Npgsql;

namespace CrdbLab.Api.Endpoints;

public class TransactionModule : ICarterModule
{
    public void AddRoutes(IEndpointRouteBuilder app)
    {
        var customerTransactions = app.MapGroup("/customers/{id:guid}/transactions").WithTags("Transactions");

        customerTransactions.MapGet("/", async (Guid id, BankDbContext db) =>
        {
            if (!await db.Customers.AnyAsync(c => c.Id == id))
                return Results.NotFound();

            var transactions = await db.Transactions.AsNoTracking()
                .Where(t => t.CustomerId == id)
                .OrderByDescending(t => t.CreatedAt)
                .Select(t => new TransactionResponse(t.Id, t.CustomerId, t.Amount, t.CreatedAt))
                .ToListAsync();

            return Results.Ok(transactions);
        })
        .Produces<List<TransactionResponse>>()
        .Produces(StatusCodes.Status404NotFound);

        customerTransactions.MapPost("/", async (Guid id, CreateTransactionRequest request, BankDbContext db) =>
        {
            if (request.Amount == 0)
                return Results.BadRequest("Amount must not be zero.");

            var transaction = new Transaction { CustomerId = id, Amount = request.Amount };
            db.Transactions.Add(transaction);

            try
            {
                await db.SaveChangesAsync(); // Id and CreatedAt are generated by CockroachDB
            }
            catch (DbUpdateException ex) when (ex.InnerException is PostgresException { SqlState: PostgresErrorCodes.ForeignKeyViolation })
            {
                return Results.NotFound("Customer not found.");
            }

            return Results.Created(
                $"/transactions/{transaction.Id}",
                new TransactionResponse(transaction.Id, transaction.CustomerId, transaction.Amount, transaction.CreatedAt));
        })
        .Produces<TransactionResponse>(StatusCodes.Status201Created)
        .Produces(StatusCodes.Status400BadRequest)
        .Produces(StatusCodes.Status404NotFound);

        app.MapGet("/transactions/{id:guid}", async (Guid id, BankDbContext db) =>
        {
            var transaction = await db.Transactions.AsNoTracking()
                .Where(t => t.Id == id)
                .Select(t => new TransactionResponse(t.Id, t.CustomerId, t.Amount, t.CreatedAt))
                .FirstOrDefaultAsync();

            return transaction is null ? Results.NotFound() : Results.Ok(transaction);
        })
        .WithTags("Transactions")
        .Produces<TransactionResponse>()
        .Produces(StatusCodes.Status404NotFound);
    }
}
